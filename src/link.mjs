// Generating the AssemblyScript entry that links several LittleScript units
// into the one module a `.lab` carries.
//
// A bundle holds exactly one script module, so a scene that uses two widget
// packages -- plus its own script -- has to end up with one. Each package's
// extension exports are renamed into the namespace the *scene* gave it, which
// is the same rename `<mx:Import as=>` applies to the component names and the
// `<mx:RunScript name=>` references, so the two halves meet in the middle.
//
// Kept apart from main.mjs because the interesting part -- which names get
// renamed to what -- is a pure string function, and testing it should not
// require running asc.

/// The four extension protocols' slugs. Mirrors `ExtensionKind::slug` in
/// crates/la-script/src/extension.rs: an export is `__la_ext_<slug>_<name>`,
/// and the namespace goes in front of `<name>`, never in front of the slug.
export const SLUGS = ["convert", "cond", "action", "path"];

export function linkModulePath(path) {
  if (path.startsWith(".") || path.startsWith("/") || /^[A-Za-z]:\//.test(path)) {
    return path;
  }
  return `./${path}`;
}

/// Entry points the host calls by a FIXED name, with their signatures.
///
/// Several units may each define one, so the entry merges them rather than
/// re-exporting whichever came last. These names are not namespaced — the host
/// asks for them literally — which is exactly why they have to be listed:
/// anything here that were treated as an ordinary export would be renamed into
/// a package's namespace and the host would never find it.
///
/// Held against the host by `crates/la-script/tests/link_entry_points.rs`.
const MERGED = [
  { name: "main", params: [] },
  { name: "onFrame", params: [] },
  { name: "onResize", params: [] },
  { name: "onEvent", params: ["kind: i32", "target: u32", "other: u32"] },
  { name: "onTouch", params: ["id: i32", "x: f32", "y: f32", "pressed: i32"] },
  { name: "__la_dispatch", params: ["callback: u32", "target: u32"] },
];
const MERGED_NAMES = MERGED.map((m) => m.name);

/// Prefix every reserved export shares. A name starting with this that no
/// protocol claims is a mistake we must not paper over.
const EXT_PREFIX = "__la_ext_";

/// Export names a unit declares, as written in its source.
///
/// The names have to be literal in the source -- they are WASM export names --
/// so reading them off `export function <name>` is exact rather than a guess.
export function exportsOf(source) {
  const found = [];
  const re = /^[ \t]*export[ \t]+function[ \t]+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(source)) !== null) found.push(m[1]);
  return found;
}

/// Rename one extension export into `namespace`.
///
/// Returns `null` for a name that is not an extension export at all — a unit's
/// own helper, which simply is not re-exported. An empty namespace is the
/// scene's own script and renames nothing.
///
/// **Throws** for a name that claims the reserved `__la_ext_` prefix but
/// matches no protocol. Returning `null` there would drop it from the linked
/// module, and the engine would answer the missing export with its fallback:
/// the widget would author cleanly, validate cleanly, and do nothing. That is
/// the failure this whole step exists to remove.
export function namespaced(name, namespace) {
  for (const slug of SLUGS) {
    const prefix = `${EXT_PREFIX}${slug}_`;
    if (name.startsWith(prefix)) {
      return namespace
        ? `${prefix}${namespace}_${name.slice(prefix.length)}`
        : name;
    }
  }
  if (name.startsWith(EXT_PREFIX) && !MERGED_NAMES.includes(name)) {
    throw new Error(
      `${name} claims the reserved ${EXT_PREFIX} prefix but names no protocol ` +
        `(expected one of ${SLUGS.join(", ")}); this linker is older than the ` +
        `engine that defines it`,
    );
  }
  return null;
}

/// The AssemblyScript source of an entry module linking `units`.
///
/// Each unit is `{ module, namespace, source }`: the lowered module to import
/// from, the namespace its extensions take, and the original source its export
/// names are read out of.
export function linkEntry(units) {
  const lines = [
    "// GENERATED by littlescript link -- do not edit.",
    "//",
    "// One module per bundle, several packages' worth of behaviour. Extension",
    "// exports are renamed into the namespace the scene gave each package, so",
    "// two vendors may both ship a `bump`.",
    "",
  ];
  const seen = new Map();
  const merged = new Map(MERGED.map((m) => [m.name, []]));
  let abi = 0;

  for (const [i, unit] of units.entries()) {
    const local = `u${i}`;
    for (const name of exportsOf(unit.source)) {
      if (MERGED_NAMES.includes(name)) {
        merged.get(name).push(`${local}_${name}`);
        lines.push(`import { ${name} as ${local}_${name} } from "${unit.module}";`);
        continue;
      }
      // Every unit may declare the ABI it was built against; the module as a
      // whole needs the HIGHEST, because a host that cannot serve one unit
      // cannot safely run the module at all.
      if (name === "__la_abi_version") {
        const declared = /__la_abi_version\(\)\s*:\s*i32\s*\{\s*return\s+(\d+)/.exec(unit.source);
        if (declared) abi = Math.max(abi, Number(declared[1]));
        continue;
      }
      const renamed = namespaced(name, unit.namespace);
      if (renamed === null) continue; // not an extension; a unit's own helper
      const owner = seen.get(renamed);
      if (owner !== undefined) {
        throw new Error(
          `two linked units both export ${renamed} (${units[owner].module} and ` +
            `${unit.module}); give them different <mx:Import as=> namespaces`,
        );
      }
      seen.set(renamed, i);
      lines.push(
        renamed === name
          ? `export { ${name} } from "${unit.module}";`
          : `export { ${name} as ${renamed} } from "${unit.module}";`,
      );
    }
  }

  for (const { name, params } of MERGED) {
    const calls = merged.get(name);
    if (calls.length === 0) continue;
    const args = params.map((p) => p.split(":")[0].trim()).join(", ");
    lines.push("");
    lines.push(`export function ${name}(${params.join(", ")}): void {`);
    for (const call of calls) lines.push(`  ${call}(${args});`);
    lines.push("}");
  }
  if (abi > 0) {
    lines.push("");
    lines.push(`export function __la_abi_version(): i32 { return ${abi}; }`);
  }
  return lines.join("\n") + "\n";
}
